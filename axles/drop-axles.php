                              <p>When an even lower ride height than that available from overlay axles is required, and produces a series of “drop” axles. This trailer industry term refers to an axle where there is a gap between the stub axle and the main structural beam, and this can vary up to a maximum of 100mm from centre of the stub axle to the centre of the beam. This is achieved by using welded “drop plates” which join the main structural beam and the stub axles. This has the effect of dramatically lowering the trailer and is typically used for such applications as race car trailers and horse floats where an easy and low access into the trailer is needed.
When considering the use of a drop axle, there are more dimensional constraints than with other types of beam axles. As the drop plates need to pass the outside of the chassis or body during suspension movement, a drop axle always needs more distance from the body to the wheel centre. Whilst this can at times be a problem, talk to your Maa Sukhrala sales contact to assist with what can be made to suit your specific dimensional needs.</p>
